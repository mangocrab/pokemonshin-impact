"""Export the approved Haerin original; codec/atlas metadata only, no repainting."""
from pathlib import Path
import json
from PIL import Image
ROOT = Path(__file__).resolve().parents[1]
im = Image.open(ROOT / 'art/source/haerin-avatar.png')
out = ROOT / 'client/public/art'
# Binary alpha in the small world-sprite export removes the generator's faint matte.
# Keep the original PNG, including original alpha, unchanged for future authoring.
im.save(out / 'haerin-avatar.webp', 'WEBP', quality=70, alpha_quality=0, method=6)
export = Image.open(out / 'haerin-avatar.webp').convert('RGBA')
alpha = export.getchannel('A')
frames = {}
width, height = im.size
cell_w, cell_h, baseline = (width + 2) // 3, height // 4, height // 4 - 8
for row, direction in enumerate(['south', 'west', 'east', 'north']):
    for col in range(3):
        left, right = round(col * width / 3), round((col + 1) * width / 3)
        top, bottom = row * cell_h, (row + 1) * cell_h
        bbox = alpha.crop((left, top, right, bottom)).getbbox()
        if bbox is None: raise ValueError('Empty avatar frame')
        x, y, r, b = bbox
        if x == 0 or r == right-left or y == 0 or b == cell_h: raise ValueError('Missing transparent gutter')
        sy = y + baseline - b
        if sy < 0 or sy + b-y > cell_h: raise ValueError('Invalid foot baseline')
        frames[f'{direction}-{col}'] = {
            'frame': {'x':left+x,'y':top+y,'w':r-x,'h':b-y}, 'rotated':False,'trimmed':True,
            'sourceSize':{'w':cell_w,'h':cell_h}, 'spriteSourceSize':{'x':x,'y':sy,'w':r-x,'h':b-y}}
atlas = {'frames':frames,'meta':{'image':'haerin-avatar.webp','size':{'w':width,'h':height},'scale':'1'}}
(out/'haerin-avatar.json').write_text(json.dumps(atlas,ensure_ascii=False,indent=2)+'\n')
manifest = {'url':'/art/haerin-avatar.webp','atlas':'/art/haerin-avatar.json','width':width,'height':height,
            'frames':{k:v['frame'] for k,v in frames.items()}}
(ROOT/'client/src/avatar-manifest.ts').write_text('// Generated by scripts/export-avatar.py.\nexport const HAERIN_AVATAR = '+json.dumps(manifest)+' as const;\n')
print('Haerin:',width,height,(out/'haerin-avatar.webp').stat().st_size,'bytes; cell',cell_w,cell_h,'foot',baseline)
print('Export alpha:',alpha.getextrema(),'levels',sum(1 for n in alpha.histogram() if n))
